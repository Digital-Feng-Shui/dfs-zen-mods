"""Puts the newest DFS mods into a Zen profile, with no switching off and on.

  python3 -I design/update-my-zen.py "<profile folder>"          waits until Zen is closed, then updates
  python3 -I design/update-my-zen.py "<profile folder>" --now    profile must already be closed (no waiting)
  ... --zen-menus   also lets Zen draw its own right-click menus (widget.macos.native-context-menus false), which
                    DFS Calm's "Shorter right-click menus" needs on a Mac

What it does, with Zen closed (Zen keeps its mod list in memory and writes it back when it quits):
1. each mod's files from this repo go into <profile>/chrome/zen-themes/<id>/ (only mods that are already in Zen's list;
   their switch stays as it is),
2. their entries in zen-themes.json get the new version, links and texts,
3. chrome/zen-themes.css, the styles Zen built from its switched-on mods, is built again from the files on disk, the
   way Zen builds it (ZenMods.mjs #writeStylesheet, Zen 1.24.3b). Zen loads that file as it starts, but only rebuilds
   it when a mod is switched, so without this the new files would wait for a switch off and on. (Zen 1.24.1b also
   rebuilt it during a mod update round at start-up; 1.24.3b dropped that round, checked 24 Nov.)
Backups land next to each file it changes (*.before-dfs-update). Read by Tinko's setup chat as the pattern for updates."""
import json, re, shutil, subprocess, sys, time
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent


def zen_running_with(profile: Path) -> bool:
    """Zen's helper processes carry the profile path in their arguments, so a profile is in use while any process names it."""
    out = subprocess.run(["ps", "-axo", "args="], capture_output=True, text=True).stdout
    return any(str(profile) in line and "update-my-zen" not in line for line in out.splitlines())  # not this script itself


def build_stylesheet(profile: Path, mods: dict) -> str:
    """Zen's own recipe: header, then each switched-on mod's chrome.css under its name, description and author."""
    stamp = time.strftime("%A, %B %-d, %Y at %-I:%M:%S %p %Z")
    out = "/* Zen Mods - Generated by ZenMods." + f"\n* FILE GENERATED AT: {stamp}\n"
    out += "* DO NOT EDIT THIS FILE DIRECTLY!\n* Your changes will be overwritten.\n* Instead, go to the preferences and edit the mods there.\n*/\n"
    for mod_id, mod in mods.items():
        if mod.get("enabled") is False: continue
        sheet = profile / "chrome/zen-themes" / mod_id / "chrome.css"
        if not sheet.exists(): continue
        out += f"\n/* Name: {mod.get('name')} */\n/* Description: {mod.get('description')} */\n/* Author: @{mod.get('author')} */\n"
        out += sheet.read_text()
    return out + "\n"


def update(profile: Path):
    entries = json.loads((REPO / "import/dfs-zen-mods.json").read_text())
    reg = profile / "zen-themes.json"
    current = json.loads(reg.read_text()) if reg.exists() else {}
    shutil.copy(reg, reg.with_name(reg.name + ".before-dfs-update"))
    done = []
    for mod_id, entry in entries.items():
        if mod_id not in current:
            continue  # only update what is there; adding is install.js's or Tinko's job
        folder = entry["homepage"].rsplit("/", 1)[1]
        dest = profile / "chrome/zen-themes" / mod_id
        dest.mkdir(parents=True, exist_ok=True)
        for f in ("chrome.css", "preferences.json", "readme.md"):
            shutil.copy(REPO / folder / f, dest / f)
        current[mod_id] = {**entry, "enabled": current[mod_id].get("enabled", True)}
        done.append(f"{entry['name']} {entry['version']}")
    reg.write_text(json.dumps(current, indent=2))
    css = profile / "chrome/zen-themes.css"
    if css.exists(): shutil.copy(css, css.with_name(css.name + ".before-dfs-update"))
    css.write_text(build_stylesheet(profile, current))
    return done


def main():
    if len(sys.argv) < 2: sys.exit(__doc__)
    profile = Path(sys.argv[1]).expanduser()
    if not (profile / "prefs.js").exists(): sys.exit(f"Not a Zen profile: {profile}")
    if "--now" not in sys.argv:
        print("Waiting for Zen to close (Cmd Q in Zen)…", flush=True)
        while zen_running_with(profile): time.sleep(1)
        time.sleep(2)  # Zen writes its files on the way out
    done = update(profile)
    if "--zen-menus" in sys.argv:
        prefs = profile / "prefs.js"; text = prefs.read_text()
        shutil.copy(prefs, prefs.with_name(prefs.name + ".before-dfs-update"))
        line = 'user_pref("widget.macos.native-context-menus", false);'
        text = re.sub(r'user_pref\("widget\.macos\.native-context-menus", (true|false)\);', line, text) if "native-context-menus" in text else text.rstrip("\n") + "\n" + line + "\n"
        prefs.write_text(text); done.append("Zen draws its own menus")
    print("Updated: " + ", ".join(done) + ". Open Zen again: the new versions load as it starts.", flush=True)


if __name__ == "__main__":
    main()
